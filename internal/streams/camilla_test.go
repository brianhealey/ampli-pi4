// Sync swaps the bridge type when EQ is toggled and pushes changes to a
// running EQ bridge, and does nothing at all for sources without EQ.
func TestManager_SyncFollowsEQChanges(t *testing.T) {
	withPhysicalOutputs(t, []int{0, 1, 2, 3})
	captureAmixer(t)
	m := NewManager(t.TempDir(), nil)
	m.SetEQBinary(filepath.Join(t.TempDir(), "camilladsp")) // missing: bridge falls back, harmless here
	ctx := context.Background()
	t.Cleanup(func() { _ = m.Shutdown(ctx) })

	streams := []models.Stream{{ID: 1002, Name: "Radio", Type: "internet_radio",
		Config: map[string]interface{}{"url": "http://example.com/stream"}}}
	conn := func() connBridge {
		m.mu.Lock()
		defer m.mu.Unlock()
		return m.conns[m.streams[1002].VSRC]
	}

	sync := func(eq *models.SourceEQ) {
		t.Helper()
		if err := m.Sync(ctx, streams, []models.Source{{ID: 1, Input: "stream=1002", EQ: eq}}); err != nil {
			t.Fatal(err)
		}
	}

	sync(nil)
	first := conn()
	if first.eq != nil || first.key != "" {
		t.Fatalf("no-EQ source got %+v", first)
	}
	sync(nil)
	if conn() != first {
		t.Error("re-sync without EQ touched the bridge")
	}

	eq := sampleEQForStreams()
	sync(eq)
	c := conn()
	if c.eq == nil {
		t.Fatal("enabling EQ did not swap to the CamillaDSP bridge")
	}
	eb := c.eq

	eq2 := sampleEQForStreams()
	eq2.Bands[0].Gain = 2
	sync(eq2)
	c = conn()
	if c.eq != eb {
		t.Error("an EQ change replaced the bridge instead of updating it")
	}
	if c.key != eqKey(eq2) {
		t.Error("key not updated")
	}
	file, _ := os.ReadFile(eb.cfgPath)
	if !strings.Contains(string(file), "gain: 2.0") {
		t.Errorf("updated config not written:\n%s", file)
	}

	off := sampleEQForStreams()
	off.Enabled = false
	sync(off)
	if c := conn(); c.eq != nil {
		t.Error("disabling EQ did not swap back to alsaloop")
	}
	eb.mu.Lock()
	stopped := eb.stopped
	eb.mu.Unlock()
	if !stopped {
		t.Error("old EQ bridge not stopped")
	}
}

func TestManager_EQStatusOwnership(t *testing.T) {
	var calls int
	var mu sync.Mutex
	m := NewManager(t.TempDir(), nil)
	m.SetEQStatusListener(func() { mu.Lock(); calls++; mu.Unlock() })
	a := &eqBridge{physSrc: 1}
	b := &eqBridge{physSrc: 1}

	m.reportEQ(a, models.EQStateStarting, "")
	m.reportEQ(a, models.EQStateStarting, "") // duplicate: no notification
	m.reportEQ(b, models.EQStateActive, "")   // new bridge on the same source
	m.reportEQ(a, "", "")                     // late stop of the old one must not clear it
	st, ok := m.EQStatus(1)
	if !ok || st.State != models.EQStateActive {
		t.Errorf("status = %+v %v", st, ok)
	}
	m.reportEQ(b, "", "")
	if _, ok := m.EQStatus(1); ok {
		t.Error("status not cleared by its owner")
	}
	mu.Lock()
	defer mu.Unlock()
	if calls != 3 {
		t.Errorf("listener called %d times, want 3", calls)
	}
}
