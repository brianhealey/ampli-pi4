// fakeBridge records Start/Stop calls.
type fakeBridge struct {
	mu      sync.Mutex
	started int
	stopped int
}

func (b *fakeBridge) Start(context.Context) error {
	b.mu.Lock()
	b.started++
	b.mu.Unlock()
	return nil
}
func (b *fakeBridge) Stop() error { b.mu.Lock(); b.stopped++; b.mu.Unlock(); return nil }
func (b *fakeBridge) counts() (int, int) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.started, b.stopped
}

// statusLog collects bridge status reports.
type statusLog struct {
	mu   sync.Mutex
	seen []string
}

func (s *statusLog) report(_ *eqBridge, state, reason string) {
	s.mu.Lock()
	s.seen = append(s.seen, state+"|"+reason)
	s.mu.Unlock()
}

func (s *statusLog) has(prefix string) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, v := range s.seen {
		if strings.HasPrefix(v, prefix) {
			return true
		}
	}
	return false
}

// fakeCamillaBinary writes a script that stays up like CamillaDSP and counts
// its starts in a file.
