func TestRateShiftResetArgs(t *testing.T) {
	cases := []struct {
		vsrc int
		card string
		dev  int // capture device of the bridge
	}{
		{0, "Loopback", 1},   // stream plays into Loopback,0
		{4, "Loopback4", 1},  // lb4c -> Loopback4,0
		{6, "Loopback", 0},   // lb6c -> Loopback,1
		{10, "Loopback4", 0}, // lb10c -> Loopback4,1; bridge reads lb10p = hw:Loopback4,0
	}
	for _, tc := range cases {
		got := rateShiftResetArgs(tc.vsrc)
		if len(got) != loopbackSubstreams {
			t.Fatalf("vsrc %d: %d commands", tc.vsrc, len(got))
		}
		for sub, args := range got {
			want := []string{"-q", "-c", tc.card, "cset",
				"iface=PCM,name='PCM Rate Shift 100000',device=" + itoa(tc.dev) + ",subdevice=" + itoa(sub),
				"100000"}
			if !reflect.DeepEqual(args, want) {
				t.Errorf("vsrc %d sub %d:\n got %q\nwant %q", tc.vsrc, sub, args, want)
			}
		}
	}
}

func itoa(i int) string { return string(rune('0' + i)) }

// captureAmixer records amixer invocations instead of running them.
func captureAmixer(t *testing.T) func() [][]string {
	t.Helper()
	var mu sync.Mutex
	var calls [][]string
	old := runAmixer
	runAmixer = func(args []string) error {
		mu.Lock()
		calls = append(calls, args)
		mu.Unlock()
		return nil
	}
	t.Cleanup(func() { runAmixer = old })
	return func() [][]string {
		mu.Lock()
		defer mu.Unlock()
		return append([][]string(nil), calls...)
	}
}

