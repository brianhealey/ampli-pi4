func TestEQBridge_LiveUpdateOverWebsocket(t *testing.T) {
	captureAmixer(t)
	bin, starts := fakeCamillaBinary(t)
	f := newFakeCamilla(t, stateReply("Running"))
	fb := &fakeBridge{}
	var st statusLog
	dir := t.TempDir()
	b := newEQBridge(2, 1, bin, dir, *sampleEQForStreams(), fb, st.report)
	b.rt = directRT() // deterministic: no chrt on the test host
	b.addr = f.addr()
	b.tune = fastSupervisor
	if err := b.Start(context.Background()); err != nil {
		t.Fatal(err)
	}
	defer b.Stop()
	if !waitFor(t, 5*time.Second, func() bool { return starts() == 1 && st.has(models.EQStateActive) }) {
		t.Fatalf("bridge did not become active: starts=%d status=%q", starts(), st.seen)
	}

	next := sampleEQForStreams()
	next.Bands[0].Gain = -4.5
	b.Update(*next)

	var pushed string
	for _, m := range f.messages() {
		if strings.HasPrefix(m, `{"SetConfig":`) {
			pushed = m
		}
	}
	if pushed == "" {
		t.Fatal("no SetConfig sent")
	}
	var body map[string]string
	if err := json.Unmarshal([]byte(pushed), &body); err != nil {
		t.Fatal(err)
	}
	if want := string(camillaConfigYAML(2, 1, *next)); body["SetConfig"] != want {
		t.Errorf("pushed config:\n%s\nwant:\n%s", body["SetConfig"], want)
	}
	file, _ := os.ReadFile(filepath.Join(dir, "v2", camillaConfigName))
	if !strings.Contains(string(file), "gain: -4.5") {
		t.Errorf("config file not rewritten:\n%s", file)
	}
	time.Sleep(100 * time.Millisecond)
	if starts() != 1 {
		t.Errorf("CamillaDSP restarted (%d starts) although the live push worked", starts())
	}
	if s, _ := fb.counts(); s != 0 {
		t.Error("fallback started")
	}
}

