func TestSupervisor_OnGiveUp(t *testing.T) {
	var mu sync.Mutex
	var reasons []string
	sup := NewSupervisor("test-giveup-hook", func() *exec.Cmd { return exec.Command("false") })
	sup.maxFails = 2
	sup.maxBackoff = 5 * time.Millisecond
	sup.onGiveUp = func(r string) { mu.Lock(); reasons = append(reasons, r); mu.Unlock() }
	_ = sup.Start(context.Background())
	if !waitFor(t, 3*time.Second, func() bool { mu.Lock(); defer mu.Unlock(); return len(reasons) == 1 }) {
		t.Fatal("onGiveUp not called")
	}
	if !strings.Contains(reasons[0], "2 times") {
		t.Errorf("reason = %q", reasons[0])
	}

	// Stop does not count as giving up.
	reasons = nil
	sleeper := NewSupervisor("test-stop", func() *exec.Cmd { return exec.Command("sleep", "30") })
	sleeper.onGiveUp = sup.onGiveUp
	_ = sleeper.Start(context.Background())
	time.Sleep(50 * time.Millisecond)
	_ = sleeper.Stop()
	mu.Lock()
	defer mu.Unlock()
	if len(reasons) != 0 {
		t.Errorf("onGiveUp called on Stop: %q", reasons)
	}
}

// ─── Bridge selection ────────────────────────────────────────────────────────

func TestManager_NewBridgeSelection(t *testing.T) {
	withPhysicalOutputs(t, []int{0, 1, 2, 3})
	enabled := sampleEQForStreams()
	disabled := sampleEQForStreams()
	disabled.Enabled = false
	sources := []models.Source{{ID: 0, EQ: enabled}, {ID: 1, EQ: disabled}, {ID: 2}}

	cases := []struct {
		name   string
		binary string
		phys   int
		wantEQ bool
	}{
		{"enabled + installed", "/usr/local/bin/camilladsp", 0, true},
		{"enabled, binary missing", "", 0, false},
		{"disabled", "/usr/local/bin/camilladsp", 1, false},
		{"no eq configured", "/usr/local/bin/camilladsp", 2, false},
	}
	for _, tc := range cases {
		m := NewManager(t.TempDir(), nil)
		m.eqBinary = tc.binary
		m.eqByPhys = effectiveEQs(sources, tc.binary)
		br, err := m.newBridge(5, tc.phys)
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		eb, isEQ := br.(*eqBridge)
		if isEQ != tc.wantEQ {
			t.Errorf("%s: got %T, want eq bridge = %v", tc.name, br, tc.wantEQ)
			continue
		}
		if isEQ {
			if eb.bin != tc.binary || eb.addr != "127.0.0.1:3805" || !strings.HasSuffix(eb.cfgPath, "/v5/camilladsp.yml") {
				t.Errorf("%s: bridge %+v", tc.name, eb)
			}
			if _, ok := eb.fallback.(*ALSALoop); !ok {
				t.Errorf("%s: fallback is %T", tc.name, eb.fallback)
			}
			continue
		}
		// The default path is exactly the pre-EQ alsaloop command.
		loop := br.(*ALSALoop)
		args := loop.sup.buildCmd().Args[1:]
		want := []string{"-C", "lb5p", "-P", "ch" + itoa(tc.phys), "-t", "100000"}
		if !reflect.DeepEqual(args, want) {
			t.Errorf("%s: alsaloop args %q, want %q", tc.name, args, want)
		}
	}
}

