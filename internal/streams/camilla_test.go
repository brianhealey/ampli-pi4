// ─── Fake CamillaDSP websocket server ────────────────────────────────────────

type fakeCamilla struct {
	ln    net.Listener
	reply func(msg string) []string // frames to send back (all but last are fragments)

	mu       sync.Mutex
	received []string
	closes   int
}

func newFakeCamilla(t *testing.T, reply func(msg string) []string) *fakeCamilla {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	f := &fakeCamilla{ln: ln, reply: reply}
	go f.serve()
	t.Cleanup(func() { ln.Close() })
	return f
}

func (f *fakeCamilla) addr() string { return f.ln.Addr().String() }

func (f *fakeCamilla) messages() []string {
	f.mu.Lock()
	defer f.mu.Unlock()
	return append([]string(nil), f.received...)
}

func (f *fakeCamilla) closeFrames() int {
	f.mu.Lock()
	defer f.mu.Unlock()
	return f.closes
}

func (f *fakeCamilla) serve() {
	for {
		c, err := f.ln.Accept()
		if err != nil {
			return
		}
		go f.handle(c)
	}
}

// writeServerFrame writes an unmasked frame, as a server must.
func writeServerFrame(c net.Conn, fin bool, op byte, payload []byte) {
	b0 := op
	if fin {
		b0 |= 0x80
	}
	hdr := []byte{b0}
	switch n := len(payload); {
	case n < 126:
		hdr = append(hdr, byte(n))
	case n <= 0xFFFF:
		hdr = append(hdr, 126)
		hdr = binary.BigEndian.AppendUint16(hdr, uint16(n))
	default:
		hdr = append(hdr, 127)
		hdr = binary.BigEndian.AppendUint64(hdr, uint64(n))
	}
	_, _ = c.Write(append(hdr, payload...))
}

func (f *fakeCamilla) handle(c net.Conn) {
	defer c.Close()
	br := bufio.NewReader(c)
	req, err := http.ReadRequest(br)
	if err != nil {
		return
	}
	key := req.Header.Get("Sec-WebSocket-Key")
	if req.Header.Get("Sec-WebSocket-Version") != "13" || key == "" {
		_, _ = c.Write([]byte("HTTP/1.1 400 Bad Request\r\n\r\n"))
		return
	}
	_, _ = c.Write([]byte("HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n" +
		"Sec-WebSocket-Accept: " + wsAccept(key) + "\r\n\r\n"))
	ws := &wsConn{conn: c, br: br}
	for {
		_ = c.SetReadDeadline(time.Now().Add(5 * time.Second))
		hb, err := br.Peek(2)
		if err != nil {
			return
		}
		if hb[1]&0x80 == 0 {
			return // client frames must be masked
		}
		_, op, payload, err := ws.readFrame()
		if err != nil {
			return
		}
		switch op {
		case wsOpClose:
			f.mu.Lock()
			f.closes++
			f.mu.Unlock()
			writeServerFrame(c, true, wsOpClose, payload)
			return
		case wsOpText:
			f.mu.Lock()
			f.received = append(f.received, string(payload))
			f.mu.Unlock()
			frames := f.reply(string(payload))
			for i, fr := range frames {
				op := byte(wsOpText)
				if i > 0 {
					op = wsOpContinue
				}
				writeServerFrame(c, i == len(frames)-1, op, []byte(fr))
			}
		}
	}
}

func stateReply(state string) func(string) []string {
	return func(msg string) []string {
		if msg == `"GetState"` {
			return []string{`{"GetState":{"result":"Ok","value":"` + state + `"}}`}
		}
		var m map[string]json.RawMessage
		_ = json.Unmarshal([]byte(msg), &m)
		for k := range m {
			return []string{`{"` + k + `":{"result":"Ok"}}`}
		}
		return []string{`{}`}
	}
}

