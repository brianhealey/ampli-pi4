// Per-source EQ runs CamillaDSP in place of alsaloop as the bridge from a
// stream's loopback (lb<vsrc>p) to its source's DAC (ch<physSrc>). Settings
// measured on the device: 48 kHz S16_LE, chunksize 1024, rate adjust against
// the loopback's "PCM Rate Shift 100000" control (CamillaDSP finds it through
// the lb<N>p plug, so no resampler is needed).

// camillaPortBase + vsrc is the CamillaDSP websocket port for a bridge. Keyed
// by vsrc rather than physSrc because vsrc is unique per running stream: two
// streams briefly sharing a source during a switch cannot collide. 3800-3811
// is unused elsewhere (AirPlay 5000/5100-6200, its UDP 6101+, Spotify
// 3678-3689). Bound to 127.0.0.1 only.
const camillaPortBase = 3800

func camillaPort(vsrc int) int { return camillaPortBase + vsrc }

// camillaConfigName is the generated config, written to srcs/v<vsrc>/.
const camillaConfigName = "camilladsp.yml"

// Bridge supervision tuning. A CamillaDSP that cannot open its devices exits
// at once (with status 0), so fast failures are the common failure mode; one
// that stays up without processing is caught by the GetState health check.
// With these values a broken bridge falls back to alsaloop within ~5 s (fast
// exits) to ~15 s (alive but not processing).
const (
	camillaMaxFails       = 3
	camillaFastFailSec    = 5.0
	camillaInitialBackoff = 500 * time.Millisecond
	camillaMaxBackoff     = 5 * time.Second
	camillaHealthGrace    = 1 * time.Second
	camillaHealthInterval = 2 * time.Second
	camillaHealthFailures = 2
	camillaCmdTimeout     = 2 * time.Second
	camillaPushTimeout    = 3 * time.Second
)

// camillaBiquadType maps the API band type to CamillaDSP's Biquad type.
var camillaBiquadType = map[string]string{
	models.EQBandPeaking:   "Peaking",
	models.EQBandLowShelf:  "Lowshelf",
	models.EQBandHighShelf: "Highshelf",
}

// yamlNum formats a float so YAML always reads it as a float ("3.0", not "3").
func yamlNum(v float64) string {
	s := strconv.FormatFloat(v, 'f', -1, 64)
	if !strings.ContainsAny(s, ".eEnN") {
		s += ".0"
	}
	return s
}

// camillaConfigYAML renders the CamillaDSP config for one bridge. It is a pure
// function of its inputs. The only user-controlled values are the EQ numbers
// and band types, which are validated before they get here; device names are
// quoted anyway. A Gain filter carries the preamp and each band becomes one
// Biquad, all applied to both channels.
func camillaConfigYAML(vsrc, physSrc int, eq models.SourceEQ) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by amplipi for the v%d -> ch%d bridge. Rewritten on every EQ change.\n", vsrc, physSrc)
	b.WriteString("devices:\n")
	b.WriteString("  samplerate: 48000\n")
	b.WriteString("  chunksize: 1024\n")
	b.WriteString("  enable_rate_adjust: true\n")
	b.WriteString("  adjust_period: 10\n")
	b.WriteString("  capture:\n")
	b.WriteString("    type: Alsa\n")
	b.WriteString("    channels: 2\n")
	fmt.Fprintf(&b, "    device: %s\n", strconv.Quote(VirtualCaptureDevice(vsrc)))
	b.WriteString("    format: S16_LE\n")
	b.WriteString("  playback:\n")
	b.WriteString("    type: Alsa\n")
	b.WriteString("    channels: 2\n")
	fmt.Fprintf(&b, "    device: %s\n", strconv.Quote(PhysicalOutputDevice(physSrc)))
	b.WriteString("    format: S16_LE\n")

	names := []string{"preamp"}
	b.WriteString("filters:\n")
	b.WriteString("  preamp:\n")
	b.WriteString("    type: Gain\n")
	b.WriteString("    parameters:\n")
	fmt.Fprintf(&b, "      gain: %s\n", yamlNum(eq.PreampDB))
	b.WriteString("      scale: dB\n")
	for i, band := range eq.Bands {
		typ, ok := camillaBiquadType[band.Type]
		if !ok {
			continue // unreachable after validation; never emit an unknown type
		}
		name := fmt.Sprintf("band_%d", i+1)
		names = append(names, name)
		fmt.Fprintf(&b, "  %s:\n", name)
		b.WriteString("    type: Biquad\n")
		b.WriteString("    parameters:\n")
		fmt.Fprintf(&b, "      type: %s\n", typ)
		fmt.Fprintf(&b, "      freq: %s\n", yamlNum(band.Freq))
		fmt.Fprintf(&b, "      gain: %s\n", yamlNum(band.Gain))
		fmt.Fprintf(&b, "      q: %s\n", yamlNum(band.Q))
	}

	b.WriteString("pipeline:\n")
	b.WriteString("  - type: Filter\n")
	b.WriteString("    channels: [0, 1]\n")
	b.WriteString("    names:\n")
	for _, n := range names {
		fmt.Fprintf(&b, "      - %s\n", n)
	}
	return b.Bytes()
}

// ─── Loopback rate shift ──────────────────────────────────────────────────────

// loopbackSubstreams is snd-aloop's pcm_substreams per card (30-alsa.sh).
const loopbackSubstreams = 2

// rateShiftResetArgs returns the amixer invocations that put the loopback's
// "PCM Rate Shift 100000" control back to 100000 for the cable the bridge on
// vsrc reads. The stream plays into device VirtualOutputPCM(vsrc) and the
// bridge captures the other device of the same card; snd-aloop keys the
// control by the capture device and substream, so it is addressed by
// iface/name/device/subdevice (numids differ per device and substream). Both
// substreams are reset because the one the bridge got is not known.
func rateShiftResetArgs(vsrc int) [][]string {
	card, playDev := VirtualOutputPCM(vsrc)
	captureDev := 1 - playDev
	out := make([][]string, 0, loopbackSubstreams)
	for sub := 0; sub < loopbackSubstreams; sub++ {
		out = append(out, []string{
			"-q", "-c", card, "cset",
			fmt.Sprintf("iface=PCM,name='PCM Rate Shift 100000',device=%d,subdevice=%d", captureDev, sub),
			"100000",
		})
	}
	return out
}

// runAmixer runs amixer with args. A variable so tests can capture calls.
var runAmixer = func(args []string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, findBinary("amixer"), args...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%w: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// resetRateShift restores the loopback's rate shift after CamillaDSP has
// used it. CamillaDSP can exit leaving it at e.g. 99999. alsaloop writes
// 100000 itself when it opens and closes the control, but only if it finds
// the control through the lb<N>p plug, which has not been verified on the
// device; a stale value would make the following bridge (or a later
// CamillaDSP) start off-rate. Failures are logged at debug: there is no
// amixer or loopback card in mock mode or on macOS.
func resetRateShift(vsrc int) {
	for _, args := range rateShiftResetArgs(vsrc) {
		if err := runAmixer(args); err != nil {
			slog.Debug("eq: could not reset loopback rate shift", "vsrc", vsrc, "args", args, "err", err)
		}
	}
}

// ─── EQ bridge ────────────────────────────────────────────────────────────────

// eqReporter receives a bridge's EQ state for its source. An empty state
// clears the entry (bridge stopped).
type eqReporter func(b *eqBridge, state, reason string)

// eqBridge runs CamillaDSP as the vsrc -> physSrc bridge, applying a source's
// EQ. If CamillaDSP cannot stay up it starts the plain alsaloop bridge
// instead, so audio keeps playing, and reports the EQ as failed.
type eqBridge struct {
	vsrc, physSrc int
	bin           string
	cfgPath       string
	addr          string
	fallback      bridge // alsaloop for the same connection, started on give-up
	report        eqReporter
	tune          func(*Supervisor) // tests shorten timings

	mu       sync.Mutex
	ctx      context.Context
	eq       models.SourceEQ
	sup      *Supervisor
	fellBack bool
	stopped  bool
}

func newEQBridge(vsrc, physSrc int, bin, configDir string, eq models.SourceEQ, fallback bridge, report eqReporter) *eqBridge {
	return &eqBridge{
		vsrc:     vsrc,
		physSrc:  physSrc,
		bin:      bin,
		cfgPath:  filepath.Join(configDir, fmt.Sprintf("v%d", vsrc), camillaConfigName),
		addr:     fmt.Sprintf("127.0.0.1:%d", camillaPort(vsrc)),
		fallback: fallback,
		report:   report,
		eq:       *eq.Clone(),
	}
}

func (b *eqBridge) name() string {
	return fmt.Sprintf("camilladsp/v%d->ch%d", b.vsrc, b.physSrc)
}

func (b *eqBridge) setStatus(state, reason string) {
	if b.report != nil {
		b.report(b, state, reason)
	}
}

// writeConfig writes the current config file. Caller holds b.mu.
func (b *eqBridge) writeConfig() ([]byte, error) {
	cfg := camillaConfigYAML(b.vsrc, b.physSrc, b.eq)
	return cfg, writeFileAtomic(b.cfgPath, cfg)
}

// Start writes the config and starts CamillaDSP under a Supervisor.
func (b *eqBridge) Start(ctx context.Context) error {
	b.mu.Lock()
	b.ctx = ctx
	if _, err := b.writeConfig(); err != nil {
		b.mu.Unlock()
		b.fallBack(fmt.Sprintf("could not write %s: %v", b.cfgPath, err))
		return nil
	}
	port := strconv.Itoa(camillaPort(b.vsrc))
	bin, cfgPath := b.bin, b.cfgPath
	sup := NewSupervisor(b.name(), func() *exec.Cmd {
		// -l warn: CamillaDSP logs every websocket connection at info, and
		// the health check connects every few seconds.
		return exec.Command(bin, "-l", "warn", "-a", "127.0.0.1", "-p", port, cfgPath)
	})
	sup.maxFails = camillaMaxFails
	sup.fastFailSec = camillaFastFailSec
	sup.initialBackoff = camillaInitialBackoff
	sup.backoff = camillaInitialBackoff
	sup.maxBackoff = camillaMaxBackoff
	sup.healthCheck = b.checkHealth
	sup.healthGrace = camillaHealthGrace
	sup.healthInterval = camillaHealthInterval
	sup.healthFailures = camillaHealthFailures
	sup.onGiveUp = b.fallBack
	sup.onExit = func(error) {
		b.mu.Lock()
		stopped := b.stopped
		b.mu.Unlock()
		if !stopped {
			b.setStatus(models.EQStateStarting, "CamillaDSP exited; restarting")
		}
	}
	if b.tune != nil {
		b.tune(sup)
	}
	b.sup = sup
	nBands := len(b.eq.Bands)
	b.mu.Unlock()

	slog.Info("eq: starting CamillaDSP bridge", "vsrc", b.vsrc, "physSrc", b.physSrc,
		"bands", nBands, "config", cfgPath, "ws", b.addr)
	b.setStatus(models.EQStateStarting, "")
	return sup.Start(ctx)
}

// checkHealth is the Supervisor health check: CamillaDSP's exit status is
// not reliable (a missing ALSA device exits 0), so it must answer GetState
// with a processing state on its websocket.
func (b *eqBridge) checkHealth() error {
	val, err := camillaCommand(b.addr, "GetState", camillaCmdTimeout)
	if err != nil {
		return err
	}
	var state string
	if err := json.Unmarshal(val, &state); err != nil {
		return fmt.Errorf("camilladsp GetState: unexpected value %s", truncate(val, 100))
	}
	switch state {
	case "Running", "Paused":
		b.setStatus(models.EQStateActive, "")
		return nil
	case "Starting":
		return nil
	default: // Inactive (no config), Stalled (capture gives no data)
		return fmt.Errorf("camilladsp state %s", state)
	}
}

// fallBack replaces CamillaDSP with alsaloop for this connection. Runs on the
// supervision goroutine (onGiveUp) or from Start.
func (b *eqBridge) fallBack(reason string) {
	b.mu.Lock()
	if b.stopped || b.fellBack {
		b.mu.Unlock()
		return
	}
	b.fellBack = true
	ctx := b.ctx
	b.mu.Unlock()

	slog.Error("eq: CamillaDSP bridge failed, falling back to alsaloop without EQ so audio keeps playing",
		"vsrc", b.vsrc, "physSrc", b.physSrc, "reason", reason)
	resetRateShift(b.vsrc)
	b.setStatus(models.EQStateFailed, "CamillaDSP "+reason+"; playing without EQ")
	if err := b.fallback.Start(ctx); err != nil {
		slog.Error("eq: fallback alsaloop failed to start", "vsrc", b.vsrc, "physSrc", b.physSrc, "err", err)
	}
}

// Update applies a changed EQ to the running bridge. The config file is
// rewritten first, so a later restart uses it; then the full config is pushed
// over the websocket (a filters-only change applies without a gap). If the
// push fails CamillaDSP is restarted with the new file. After a fallback the
// file is updated but alsaloop keeps running until the next reconnect.
func (b *eqBridge) Update(eq models.SourceEQ) {
	b.mu.Lock()
	b.eq = *eq.Clone()
	cfg, err := b.writeConfig()
	if err != nil {
		slog.Warn("eq: could not rewrite CamillaDSP config", "path", b.cfgPath, "err", err)
	}
	stopped, fell, sup := b.stopped, b.fellBack, b.sup
	b.mu.Unlock()
	if stopped || fell || sup == nil {
		return
	}

	_, err = camillaCommand(b.addr, map[string]any{"SetConfig": string(cfg)}, camillaPushTimeout)
	if err == nil {
		slog.Info("eq: applied new EQ live", "vsrc", b.vsrc, "physSrc", b.physSrc, "bands", len(eq.Bands))
		return
	}
	slog.Warn("eq: live EQ update failed, restarting CamillaDSP", "vsrc", b.vsrc, "physSrc", b.physSrc, "err", err)

	_ = sup.Stop()
	b.mu.Lock()
	if b.stopped || b.fellBack {
		b.mu.Unlock()
		return
	}
	ctx := b.ctx
	b.mu.Unlock()
	b.setStatus(models.EQStateStarting, "restarting with new settings")
	_ = sup.Start(ctx)
}

// Stop ends CamillaDSP (or the fallback alsaloop) and resets the loopback's
// rate shift.
func (b *eqBridge) Stop() error {
	b.mu.Lock()
	if b.stopped {
		b.mu.Unlock()
		return nil
	}
	b.stopped = true
	sup := b.sup
	b.mu.Unlock()

	slog.Info("eq: stopping CamillaDSP bridge", "vsrc", b.vsrc, "physSrc", b.physSrc)
	if sup != nil {
		_ = sup.Stop() // waits for the supervision goroutine, so no fallBack is in flight after this
	}
	b.mu.Lock()
	fell := b.fellBack
	b.mu.Unlock()
	if fell {
		_ = b.fallback.Stop()
	}
	resetRateShift(b.vsrc)
	b.setStatus("", "")
	return nil
}
